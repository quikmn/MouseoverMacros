        { "gheal", "Greater Heal", { 2060, 10963, 10964, 10965, 25314 } },
    }
    local set = ns.MACROS.PRIEST
    for _, r in ipairs(RANKS) do
        for n = 1, #r[3] - 1 do
            set[#set + 1] = { r[1] .. "r" .. n, r[2], "help", id = r[3][n], rank = n, on = false,
                why = "rank " .. n .. ": a cheaper, smaller heal" }
        end
    end
end

